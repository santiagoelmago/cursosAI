function resolve(obj: any, path: string): string {
  return path.split('.').reduce((acc, k) => acc?.[k], obj) ?? path;
}

const initial: Locale = browser ? ((localStorage.getItem('locale') as Locale) ?? 'en') : 'en';

export const locale = writable<Locale>(initial);

if (browser) {
  locale.subscribe((v) => localStorage.setItem('locale', v));
}

export const t = derived(locale, ($locale) => (key: string, params?: Record<string, string | number>): string => {
  let result = resolve(messages[$locale], key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      result = result.replaceAll(`{${k}}`, String(v));
    }
  }
  return result;
});
